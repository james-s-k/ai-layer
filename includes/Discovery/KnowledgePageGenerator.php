	/** @return array<string> */
	private function build_header_lines(): array {
		$name = $this->site_name();

		return [
			"# {$name} — Complete Business Knowledge",
			'',
			'> ' . $this->site_description(),
			'',
			'**Last updated:** ' . $this->updated_at_label(),
			'**HTML version:** ' . home_url( '/ai-layer/knowledge' ),
			'**Markdown version:** ' . home_url( '/ai-layer/knowledge.md' ),
			'**Structured API:** ' . rest_url( WPAIL_REST_NS . '/manifest' ),
			'',
			'## Contents',
			'',
			'- [Business profile](#profile)',
			'- [Services](#services)',
			'- [Locations](#locations)',
			'- [FAQs](#faqs)',
			'- [Proof and trust](#proof)',
			'- [Actions](#actions)',
			...( Features::answers_enabled() ? [ '- [Authored answers](#answers)', '' ] : [ '' ] ),
		];
	}

	/** @return array<string> */
	private function build_profile_md(): array {
		$p     = $this->profile;
		$lines = [ '## Business profile {#profile}', '' ];

		$this->append_md_field( $lines, 'Name', $p->name );
		$this->append_md_field( $lines, 'Legal name', $p->legal_name );
		$this->append_md_field( $lines, 'Type', trim( $p->business_type . ( $p->subtype ? " ({$p->subtype})" : '' ) ) );
		$this->append_md_field( $lines, 'Summary', $p->short_summary );
		if ( $p->long_summary ) {
			$lines[] = $p->long_summary;
			$lines[] = '';
		}
		$this->append_md_field( $lines, 'Phone', $p->phone );
		$this->append_md_field( $lines, 'Email', $p->email );
		$this->append_md_field( $lines, 'Website', $p->website );
		$address = $this->format_address( $p );
		if ( $address ) {
			$lines[] = '**Address:** ' . $address;
			$lines[] = '';
		}
		$this->append_md_field( $lines, 'Opening hours', $p->opening_hours );
		$this->append_md_list( $lines, 'Service modes', $p->service_modes );
		$this->append_md_field( $lines, 'Trust summary', $p->trust_summary );

		$social = array_filter( [
			'Facebook'  => $p->social_facebook,
			'Twitter/X' => $p->social_twitter,
			'LinkedIn'  => $p->social_linkedin,
			'Instagram' => $p->social_instagram,
			'YouTube'   => $p->social_youtube,
		] );
		if ( ! empty( $social ) ) {
			$lines[] = '**Social:**';
			foreach ( $social as $label => $url ) {
				$lines[] = "- {$label}: {$url}";
			}
			$lines[] = '';
		}

		return $lines;
	}

	/** @return array<string> */
	private function build_services_md(): array {
		$lines = [ '## Services {#services}', '' ];
		if ( empty( $this->services ) ) {
			$lines[] = '_No services published._';
			$lines[] = '';
			return $lines;
		}

		foreach ( $this->services as $service ) {
			$anchor = 'service-' . $service->slug;
			$lines[] = "### {$service->name} {#{$anchor}}";
			$lines[] = '';
			$this->append_md_field( $lines, 'Category', $service->category );
			$this->append_md_field( $lines, 'Summary', $service->short_summary );
			if ( $service->long_summary ) {
				$lines[] = $service->long_summary;
				$lines[] = '';
			}
			$this->append_md_list( $lines, 'Keywords', $service->keywords );
			$this->append_md_list( $lines, 'Customer types', $service->customer_types );
			$this->append_md_list( $lines, 'Service modes', $service->service_modes );
			$this->append_md_list( $lines, 'Benefits', $service->benefits );
			if ( $service->pricing_type || null !== $service->from_price ) {
				$price = $service->pricing_type;
				if ( null !== $service->from_price ) {
					$price .= ' from ' . $service->from_price . ' ' . $service->currency;
				}
				if ( $service->price_notes ) {
					$price .= ' — ' . $service->price_notes;
				}
				$lines[] = '**Pricing:** ' . trim( $price );
				$lines[] = '';
			}
			$this->append_md_field( $lines, 'Related FAQs', $this->names_for_ids( $service->related_faq_ids, $this->faq_titles ) );
			$this->append_md_field( $lines, 'Related locations', $this->names_for_ids( $service->related_location_ids, $this->location_names ) );
			$this->append_md_field( $lines, 'Related proof', $this->names_for_ids( $service->related_proof_ids, $this->proof_titles ) );
			$this->append_md_field( $lines, 'Related actions', $this->names_for_ids( $service->related_action_ids, $this->action_labels ) );
			if ( $service->linked_page_url ) {
				$lines[] = '**Linked page:** ' . $service->linked_page_url;
				$lines[] = '';
			}
		}

		return $lines;
	}

	/** @return array<string> */
	private function build_locations_md(): array {
		$lines = [ '## Locations {#locations}', '' ];
		if ( empty( $this->locations ) ) {
			$lines[] = '_No locations published._';
			$lines[] = '';
			return $lines;
		}

		foreach ( $this->locations as $location ) {
			$lines[] = "### {$location->name} {#location-{$location->slug}}";
			$lines[] = '';
			$this->append_md_field( $lines, 'Type', $location->location_type );
			$this->append_md_field( $lines, 'Region', $location->region );
			$this->append_md_field( $lines, 'Country', $location->country );
			$this->append_md_list( $lines, 'Postcode prefixes', $location->postcode_prefixes );
			if ( $location->is_primary ) {
				$lines[] = '**Primary location:** yes';
				$lines[] = '';
			}
			if ( null !== $location->service_radius_km ) {
				$lines[] = '**Service radius:** ' . $location->service_radius_km . ' km';
				$lines[] = '';
			}
			$this->append_md_field( $lines, 'Summary', $location->summary );
			$this->append_md_field( $lines, 'Related services', $this->names_for_ids( $location->related_service_ids, $this->service_names ) );
			$this->append_md_field( $lines, 'Local proof', $this->names_for_ids( $location->local_proof_ids, $this->proof_titles ) );
		}

		return $lines;
	}

	/** @return array<string> */
	private function build_faqs_md(): array {
		$lines = [ '## FAQs {#faqs}', '' ];
		if ( empty( $this->faqs ) ) {
			$lines[] = '_No FAQs published._';
			$lines[] = '';
			return $lines;
		}

		foreach ( $this->faqs as $faq ) {
			$lines[] = "### {$faq->question} {#faq-{$faq->id}}";
			$lines[] = '';
			$lines[] = $faq->short_answer;
			$lines[] = '';
			if ( $faq->long_answer ) {
				$lines[] = $faq->long_answer;
				$lines[] = '';
			}
			$this->append_md_field( $lines, 'Related services', $this->names_for_ids( $faq->related_service_ids, $this->service_names ) );
			$this->append_md_field( $lines, 'Related locations', $this->names_for_ids( $faq->related_location_ids, $this->location_names ) );
		}

		return $lines;
	}

	/** @return array<string> */
	private function build_proof_md(): array {
		$lines = [ '## Proof and trust {#proof}', '' ];
		if ( empty( $this->proof ) ) {
			$lines[] = '_No proof items published._';
			$lines[] = '';
			return $lines;
		}

		foreach ( $this->proof as $item ) {
			$lines[] = "### {$item->headline} {#proof-{$item->id}}";
			$lines[] = '';
			$this->append_md_field( $lines, 'Type', $item->proof_type );
			if ( $item->content ) {
				$lines[] = $item->content;
				$lines[] = '';
			}
			$this->append_md_field( $lines, 'Source', trim( $item->source_name . ( $item->source_context ? " ({$item->source_context})" : '' ) ) );
			if ( null !== $item->rating ) {
				$lines[] = '**Rating:** ' . $item->rating;
				$lines[] = '';
			}
			$this->append_md_field( $lines, 'Related services', $this->names_for_ids( $item->related_service_ids, $this->service_names ) );
			$this->append_md_field( $lines, 'Related locations', $this->names_for_ids( $item->related_location_ids, $this->location_names ) );
		}

		return $lines;
	}

	/** @return array<string> */
	private function build_actions_md(): array {
		$lines = [ '## Actions {#actions}', '' ];
		if ( empty( $this->actions ) ) {
			$lines[] = '_No actions published._';
			$lines[] = '';
			return $lines;
		}

		foreach ( $this->actions as $action ) {
			$lines[] = "### {$action->label} {#action-{$action->id}}";
			$lines[] = '';
			$this->append_md_field( $lines, 'Type', $action->action_type );
			$this->append_md_field( $lines, 'Description', $action->description );
			if ( $action->phone ) {
				$lines[] = '**Phone:** ' . $action->phone;
				$lines[] = '';
			}
			if ( $action->url ) {
				$lines[] = '**URL:** ' . $action->url;
				$lines[] = '';
			}
			$this->append_md_field( $lines, 'Method', $action->method );
			$this->append_md_field( $lines, 'Related services', $this->names_for_ids( $action->related_service_ids, $this->service_names ) );
			$this->append_md_field( $lines, 'Related locations', $this->names_for_ids( $action->related_location_ids, $this->location_names ) );
		}

		return $lines;
	}

	/** @return array<string> */
	private function build_answers_md(): array {
		if ( ! Features::answers_enabled() ) {
			return [];
		}

		$lines = [ '## Authored answers {#answers}', '' ];
		if ( empty( $this->answers ) ) {
			$lines[] = '_No authored answers published._';
			$lines[] = '';
			return $lines;
		}

		foreach ( $this->answers as $index => $answer ) {
			$title = $answer->short_answer ?: __( 'Authored answer', 'ai-layer' );
			$lines[] = '### ' . wp_trim_words( $title, 12, '…' ) . ' {#answer-' . ( $answer->post_id ?? $index ) . '}';
			$lines[] = '';
			$this->append_md_field( $lines, 'Short answer', $answer->short_answer );
			if ( $answer->long_answer ) {
				$lines[] = $answer->long_answer;
				$lines[] = '';
			}
			$this->append_md_list( $lines, 'Query patterns', $answer->query_patterns );
			$this->append_md_field( $lines, 'Related services', $this->names_for_ids( $answer->related_service_ids, $this->service_names ) );
			$this->append_md_field( $lines, 'Related locations', $this->names_for_ids( $answer->related_location_ids, $this->location_names ) );
			$this->append_md_field( $lines, 'Next actions', $this->names_for_ids( $answer->next_action_ids, $this->action_labels ) );
			$this->append_md_field( $lines, 'Source FAQs', $this->names_for_ids( $answer->source_faq_ids, $this->faq_titles ) );
		}

		return $lines;
	}

	private function build_toc_html(): string {
		$items = [
			'profile'   => __( 'Business profile', 'ai-layer' ),
			'services'  => __( 'Services', 'ai-layer' ),
			'locations' => __( 'Locations', 'ai-layer' ),
			'faqs'      => __( 'FAQs', 'ai-layer' ),
			'proof'     => __( 'Proof and trust', 'ai-layer' ),
			'actions'   => __( 'Actions', 'ai-layer' ),
		];
		if ( Features::answers_enabled() ) {
			$items['answers'] = __( 'Authored answers', 'ai-layer' );
		}

		$html = '<nav class="toc" aria-label="' . esc_attr__( 'Contents', 'ai-layer' ) . '"><strong>' . esc_html__( 'Contents', 'ai-layer' ) . '</strong><ul>';
		foreach ( $items as $id => $label ) {
			$html .= '<li><a href="#' . esc_attr( $id ) . '">' . esc_html( $label ) . '</a></li>';
		}
		$html .= '</ul></nav>';

		return $html;
	}

	private function build_body_html(): string {
		$html  = $this->build_profile_html();
		$html .= $this->build_services_html();
		$html .= $this->build_locations_html();
		$html .= $this->build_faqs_html();
		$html .= $this->build_proof_html();
		$html .= $this->build_actions_html();
		$html .= $this->build_answers_html();

		return $html;
	}

	private function build_profile_html(): string {
		$p = $this->profile;

		return $this->section_open( 'profile', __( 'Business profile', 'ai-layer' ) )
			. $this->entity_dl( [
				__( 'Name', 'ai-layer' )           => $p->name,
				__( 'Legal name', 'ai-layer' )     => $p->legal_name,
				__( 'Type', 'ai-layer' )           => trim( $p->business_type . ( $p->subtype ? " ({$p->subtype})" : '' ) ),
				__( 'Summary', 'ai-layer' )        => $p->short_summary,
				__( 'Phone', 'ai-layer' )          => $p->phone,
				__( 'Email', 'ai-layer' )          => $p->email,
				__( 'Website', 'ai-layer' )        => $p->website,
				__( 'Address', 'ai-layer' )        => $this->format_address( $p ),
				__( 'Opening hours', 'ai-layer' )  => $p->opening_hours,
				__( 'Service modes', 'ai-layer' )  => implode( ', ', $p->service_modes ),
				__( 'Trust summary', 'ai-layer' )  => $p->trust_summary,
			] )
			. ( $p->long_summary ? '<p>' . esc_html( $p->long_summary ) . '</p>' : '' )
			. $this->section_close();
	}

	private function build_services_html(): string {
		$html = $this->section_open( 'services', __( 'Services', 'ai-layer' ) );
		if ( empty( $this->services ) ) {
			return $html . '<p><em>' . esc_html__( 'No services published.', 'ai-layer' ) . '</em></p>' . $this->section_close();
		}

		foreach ( $this->services as $service ) {
			$html .= '<article class="entity" id="service-' . esc_attr( $service->slug ) . '">';
			$html .= '<h3>' . esc_html( $service->name ) . '</h3>';
			$html .= $this->entity_dl( [
				__( 'Category', 'ai-layer' )          => $service->category,
				__( 'Summary', 'ai-layer' )           => $service->short_summary,
				__( 'Keywords', 'ai-layer' )          => implode( ', ', $service->keywords ),
				__( 'Related FAQs', 'ai-layer' )      => $this->names_for_ids( $service->related_faq_ids, $this->faq_titles ),
				__( 'Related locations', 'ai-layer' ) => $this->names_for_ids( $service->related_location_ids, $this->location_names ),
				__( 'Related proof', 'ai-layer' )     => $this->names_for_ids( $service->related_proof_ids, $this->proof_titles ),
				__( 'Related actions', 'ai-layer' )   => $this->names_for_ids( $service->related_action_ids, $this->action_labels ),
			] );
			if ( $service->long_summary ) {
				$html .= '<p>' . esc_html( $service->long_summary ) . '</p>';
			}
			$html .= '</article>';
		}

		return $html . $this->section_close();
	}

	private function build_locations_html(): string {
		$html = $this->section_open( 'locations', __( 'Locations', 'ai-layer' ) );
		if ( empty( $this->locations ) ) {
			return $html . '<p><em>' . esc_html__( 'No locations published.', 'ai-layer' ) . '</em></p>' . $this->section_close();
		}

		foreach ( $this->locations as $location ) {
			$html .= '<article class="entity" id="location-' . esc_attr( $location->slug ) . '">';
			$html .= '<h3>' . esc_html( $location->name ) . '</h3>';
