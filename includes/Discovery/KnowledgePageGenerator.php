	/** @return array<string, mixed> */
	private function build_json_ld(): array {
		$graph = [];

		$p = $this->profile;
		if ( $p->name ) {
			$org = [
				'@type'       => 'Organization',
				'name'        => $p->name,
				'description' => $p->short_summary,
				'url'         => $p->website ?: home_url(),
			];
			if ( $p->phone ) {
				$org['telephone'] = $p->phone;
			}
			$graph[] = $org;
		}

		if ( ! empty( $this->faqs ) ) {
			$graph[] = [
				'@type'      => 'FAQPage',
				'mainEntity' => array_map(
					static fn( FaqModel $faq ) => [
						'@type'          => 'Question',
						'name'           => $faq->question,
						'acceptedAnswer' => [
							'@type' => 'Answer',
							'text'  => $faq->short_answer,
						],
					],
					$this->faqs
				),
			];
		}

		if ( empty( $graph ) ) {
			return [];
		}

		return [
			'@context' => 'https://schema.org',
			'@graph'   => $graph,
		];
	}

	private function section_open( string $id, string $title ): string {
		return '<section id="' . esc_attr( $id ) . '"><h2>' . esc_html( $title ) . '</h2>';
	}

	private function section_close(): string {
		return '</section>';
	}

	/** @param array<string, string> $fields */
	private function entity_dl( array $fields ): string {
		$html = '<dl>';
		foreach ( $fields as $label => $value ) {
			$value = trim( $value );
			if ( '' === $value ) {
				continue;
			}
			$html .= '<dt>' . esc_html( $label ) . '</dt><dd>' . esc_html( $value ) . '</dd>';
		}
		$html .= '</dl>';

		return $html;
	}

	/** @param array<string> $lines */
	private function append_md_field( array &$lines, string $label, string $value ): void {
		$value = trim( $value );
		if ( '' === $value ) {
			return;
		}
		$lines[] = "**{$label}:** {$value}";
		$lines[] = '';
	}

	/** @param array<string> $lines @param array<string> $items */
	private function append_md_list( array &$lines, string $label, array $items ): void {
		$items = array_values( array_filter( array_map( 'trim', $items ) ) );
		if ( empty( $items ) ) {
			return;
		}
		$lines[] = "**{$label}:** " . implode( ', ', $items );
		$lines[] = '';
	}

	/** @param array<int> $ids @param array<int, string> $map */
	private function names_for_ids( array $ids, array $map ): string {
		$names = [];
		foreach ( $ids as $id ) {
			if ( isset( $map[ (int) $id ] ) ) {
				$names[] = $map[ (int) $id ];
			}
		}

		return implode( ', ', $names );
	}

	private function format_address( BusinessModel $profile ): string {
		$parts = array_filter( [
			$profile->address_line1,
			$profile->address_line2,
			$profile->city,
			$profile->county,
			$profile->postcode,
			$profile->country,
		] );

		return implode( ', ', $parts );
	}

	private function site_name(): string {
		return $this->profile->name ?: get_bloginfo( 'name' );
	}

	private function site_description(): string {
		$desc = $this->profile->short_summary ?: get_bloginfo( 'description' );

		return $desc ?: __( 'Complete structured business knowledge for this site.', 'ai-layer' );
	}

	private function updated_at_label(): string {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
		$max = $wpdb->get_var(
			$wpdb->prepare(
				"SELECT MAX(post_modified_gmt) FROM {$wpdb->posts} WHERE post_type IN (%s,%s,%s,%s,%s,%s) AND post_status = 'publish'",
				'wpail_service',
				'wpail_location',
				'wpail_faq',
				'wpail_proof',
				'wpail_action',
				'wpail_answer'
			)
		);

		return $max ? get_date_from_gmt( $max, 'c' ) : gmdate( 'c' );
	}
