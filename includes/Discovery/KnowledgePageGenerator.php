			$html .= '<article class="entity" id="answer-' . esc_attr( (string) $id ) . '">';
			$html .= '<h3>' . esc_html( wp_trim_words( $answer->short_answer ?: __( 'Authored answer', 'ai-layer' ), 12, '…' ) ) . '</h3>';
