<?php
/**
 * Builds the full business knowledge export (Markdown and HTML).
 *
 * @package WPAIL\Discovery
 */

declare(strict_types=1);

namespace WPAIL\Discovery;

use WPAIL\Licensing\Features;
use WPAIL\Models\ActionModel;
use WPAIL\Models\AnswerModel;
use WPAIL\Models\BusinessModel;
use WPAIL\Models\FaqModel;
use WPAIL\Models\LocationModel;
use WPAIL\Models\ProofModel;
use WPAIL\Models\ServiceModel;
use WPAIL\Repositories\ActionRepository;
use WPAIL\Repositories\AnswerRepository;
use WPAIL\Repositories\BusinessRepository;
use WPAIL\Repositories\FaqRepository;
use WPAIL\Repositories\LocationRepository;
use WPAIL\Repositories\ProofRepository;
use WPAIL\Repositories\ServiceRepository;

class KnowledgePageGenerator {

	private BusinessModel $profile;

	/** @var array<ServiceModel> */
	private array $services;

	/** @var array<LocationModel> */
	private array $locations;

	/** @var array<FaqModel> */
	private array $faqs;

	/** @var array<ProofModel> */
	private array $proof;

	/** @var array<ActionModel> */
	private array $actions;

	/** @var array<AnswerModel> */
	private array $answers;

	/** @var array<int, string> */
	private array $service_names = [];

	/** @var array<int, string> */
	private array $location_names = [];

	/** @var array<int, string> */
	private array $faq_titles = [];

	/** @var array<int, string> */
	private array $proof_titles = [];

	/** @var array<int, string> */
	private array $action_labels = [];

	public function __construct() {
		$this->profile   = ( new BusinessRepository() )->get();
		$this->services  = ( new ServiceRepository() )->get_all();
		$this->locations = ( new LocationRepository() )->get_all();
		$this->faqs      = ( new FaqRepository() )->get_all( true );
		$this->proof     = ( new ProofRepository() )->get_all( true );
		$this->actions   = ( new ActionRepository() )->get_all( true );
		$this->answers   = Features::answers_enabled() ? ( new AnswerRepository() )->get_all() : [];

		foreach ( $this->services as $service ) {
			$this->service_names[ $service->id ] = $service->name;
		}
		foreach ( $this->locations as $location ) {
			$this->location_names[ $location->id ] = $location->name;
		}
		foreach ( $this->faqs as $faq ) {
			$this->faq_titles[ $faq->id ] = $faq->question;
		}
		foreach ( $this->proof as $item ) {
			$this->proof_titles[ $item->id ] = $item->headline;
		}
		foreach ( $this->actions as $action ) {
			$this->action_labels[ $action->id ] = $action->label;
		}
	}

	public function generate_markdown(): string {
		$lines   = $this->build_header_lines();
		$lines   = array_merge( $lines, $this->build_profile_md() );
		$lines   = array_merge( $lines, $this->build_services_md() );
		$lines   = array_merge( $lines, $this->build_locations_md() );
		$lines   = array_merge( $lines, $this->build_faqs_md() );
		$lines   = array_merge( $lines, $this->build_proof_md() );
		$lines   = array_merge( $lines, $this->build_actions_md() );
		$lines   = array_merge( $lines, $this->build_answers_md() );
		$lines[] = '';
		$lines[] = '---';
		$lines[] = '';
		$lines[] = '_Generated by [AI Layer for WordPress](https://wordpress.org/plugins/ai-layer/). Structured API: ' . rest_url( WPAIL_REST_NS . '/manifest' ) . '_';

		return implode( "\n", $lines ) . "\n";
	}

